//! Option specs (exact spellings, see `opts`) for every git subcommand whose
//! verdict depends on its options. Taken from `git <cmd> -h` (git 2.39) plus
//! the `--no-*` negations the policies tolerate. An option missing here is
//! refused with "spell it in full"; add it here (and to the policy, if it
//! matters) rather than loosening the parser.
//!
//! Must NOT: list an option whose effect the command's policy ignores when it
//! matters (e.g. a `--no-dry-run` that would cancel a dry run).

/// A spec: groups of entries (shared groups avoid copy-paste).
pub type Spec = &'static [&'static [&'static str]];

/// The spec for `sub`, if the shim inspects its options.
pub fn of(sub: &str) -> Option<Spec> {
    Some(match sub {
        "push" => &[PUSH],
        "fetch" => &[FETCH_COMMON, FETCH],
        "pull" => &[FETCH_COMMON, PULL],
        "checkout" => &[SWITCH_COMMON, CHECKOUT],
        "switch" => &[SWITCH_COMMON, SWITCH],
        "branch" => &[BRANCH],
        "tag" => &[TAG],
        "reset" => &[RESET],
        "clean" => &[CLEAN],
        "restore" => &[RESTORE],
        "update-ref" => &[UPDATE_REF],
        "symbolic-ref" => &[SYMBOLIC_REF],
        "config" => &[CONFIG],
        "rebase" => &[REBASE],
        "read-tree" => &[READ_TREE],
        "rm" => &[RM],
        _ => return None,
    })
}

