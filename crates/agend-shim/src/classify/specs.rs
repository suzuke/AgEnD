#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn specs_are_well_formed() {
        for sub in [
            "push",
            "fetch",
            "pull",
            "checkout",
            "switch",
            "branch",
            "tag",
            "reset",
            "clean",
            "restore",
            "update-ref",
            "symbolic-ref",
            "config",
            "rebase",
            "read-tree",
            "rm",
        ] {
            let mut seen = std::collections::HashSet::new();
            for e in of(sub).unwrap().iter().flat_map(|g| g.iter()) {
                assert!(e.starts_with('-') && !e.contains(' '), "{sub}: {e:?}");
                for part in e.trim_end_matches(['=', '?', '*']).split('|') {
                    assert!(seen.insert(part), "{sub}: {part} listed twice");
                }
            }
        }
    }
}
